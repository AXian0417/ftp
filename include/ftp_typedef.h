/*
    Log levels. CONFIG_FTP_LOG_LEVEL (Kconfig) removes the lower levels at compile time.
    A source that logs defines FTP_LOG_TAG (string) and, for the default printf output,
    'static _Atomic uint32_t ftp_log_ms' (milliseconds, counted from its pulse_1ms).
*/
typedef enum ftp_log_level
{
    FTP_LOG_LEVEL_ERROR = 1,
    FTP_LOG_LEVEL_WARN,
    FTP_LOG_LEVEL_INFO,
    FTP_LOG_LEVEL_DEBUG,
    FTP_LOG_LEVEL_VERBOSE,
} ftp_log_level_t;

#if CONFIG_FTP_LOG_CUSTOM_IMPL
    /* fmt has no line ending, the implementation adds level, time and newline */
    extern void ftp_log_output(ftp_log_level_t level, const char* tag, const char* fmt, ...);
    #define FTP_LOG_OUT(lv, c, fmt, ...)        ftp_log_output(lv, FTP_LOG_TAG, fmt, ##__VA_ARGS__)
#else
    #include <stdio.h>
    #include <stdatomic.h>
    /* "I (5012) ftp: message" */
    #define FTP_LOG_OUT(lv, c, fmt, ...)        printf(c " (%lu) %s: " fmt "\n", \
        (unsigned long)atomic_load_explicit(&ftp_log_ms, memory_order_relaxed), FTP_LOG_TAG, ##__VA_ARGS__)
#endif

#if CONFIG_FTP_LOG_LEVEL >= 1
    #define FTP_LOGE(fmt, ...)                  FTP_LOG_OUT(FTP_LOG_LEVEL_ERROR, "E", fmt, ##__VA_ARGS__)
#else
    #define FTP_LOGE(fmt, ...)                  ((void)0)
#endif

#if CONFIG_FTP_LOG_LEVEL >= 2
    #define FTP_LOGW(fmt, ...)                  FTP_LOG_OUT(FTP_LOG_LEVEL_WARN, "W", fmt, ##__VA_ARGS__)
#else
    #define FTP_LOGW(fmt, ...)                  ((void)0)
#endif

#if CONFIG_FTP_LOG_LEVEL >= 3
    #define FTP_LOGI(fmt, ...)                  FTP_LOG_OUT(FTP_LOG_LEVEL_INFO, "I", fmt, ##__VA_ARGS__)
#else
    #define FTP_LOGI(fmt, ...)                  ((void)0)
#endif

#if CONFIG_FTP_LOG_LEVEL >= 4
    #define FTP_LOGD(fmt, ...)                  FTP_LOG_OUT(FTP_LOG_LEVEL_DEBUG, "D", fmt, ##__VA_ARGS__)
#else
    #define FTP_LOGD(fmt, ...)                  ((void)0)
#endif

#if CONFIG_FTP_LOG_LEVEL >= 5
    #define FTP_LOGV(fmt, ...)                  FTP_LOG_OUT(FTP_LOG_LEVEL_VERBOSE, "V", fmt, ##__VA_ARGS__)
#else
    #define FTP_LOGV(fmt, ...)                  ((void)0)
#endif

