typedef enum ftp_cmd
{
    FTP_CMD_NOT_SUPPORTED = -1,
    FTP_CMD_FEAT = 0,       /** Features */
    FTP_CMD_SYST,           /** System type */
    FTP_CMD_CDUP,           /** Change to root directory */
    FTP_CMD_CWD,            /** Change working directory */
    FTP_CMD_PWD,            /** Print working directory */
    FTP_CMD_XPWD,           /** Print the current working directory */
    FTP_CMD_SIZE,           /** Get the size of the file */
    FTP_CMD_MDTM,           /** Get the last modification time of the file */
    FTP_CMD_MFMT,           /** Modify the last modification time of the file */
    FTP_CMD_TYPE,           /** Set the transmission mode (ASCII/binary) */
    FTP_CMD_USER,           /** Login user */
    FTP_CMD_PASS,           /** Login pass */
    FTP_CMD_PASV,           /** Passive mode */
    FTP_CMD_LIST,           /** List files in the current directory */
    FTP_CMD_RETR,           /** Transfer a copy of the file */
    FTP_CMD_STOR,           /** Receive data and store it as a file on the FTP */
    FTP_CMD_DELE,           /** Delete the file */
    FTP_CMD_RMD,            /** Remove the directory */
    FTP_CMD_MKD,            /** Create the directory */
    FTP_CMD_RNFR,           /** Rename from ... */
    FTP_CMD_RNTO,           /** Rename to ... */
    FTP_CMD_NOOP,           /** No operation, used to maintain the connection */
    FTP_CMD_QUIT,           /** Disconnect */
    FTP_CMD_APPE,           /** Add data to the end of the file */
    FTP_CMD_NLST,           /** Returns a list of file names in the specified directory */
    FTP_CMD_AUTH,           /** Authentication */
    FTP_CMD_STAT,           /** Server Status */
    FTP_CMD_OPTS,           /** Options (OPTS UTF8 ON) */
    FTP_CMD_ABOR,           /** Abort the transfer in progress */
    FTP_CMD_MODE,           /** Transfer mode (only S, stream) */
    FTP_CMD_STRU,           /** File structure (only F, file) */
    FTP_CMD_ALLO,           /** Allocate storage (not needed) */
    FTP_CMD_EPSV,           /** Extended passive mode (RFC 2428, port only) */
    FTP_CMD_REST,           /** Restart the next RETR/STOR at an offset (RFC 3659 stream mode) */
    FTP_CMDS_MAX,           /** Number of commands */
} ftp_cmd_t;

/**
 * @brief Get the command keyword
 *
 * @param cmd Command
 *
 * @return const char* Keyword, "" if cmd is out of range
 *
 * @note Shared by server and client without a separate source file
 */
static inline const char* ftp_cmd_name(ftp_cmd_t cmd)
{
    static const char* const names[FTP_CMDS_MAX] =
    {
        [FTP_CMD_FEAT] = "FEAT",
        [FTP_CMD_SYST] = "SYST",
        [FTP_CMD_CDUP] = "CDUP",
        [FTP_CMD_CWD] = "CWD",
        [FTP_CMD_PWD] = "PWD",
        [FTP_CMD_XPWD] = "XPWD",
        [FTP_CMD_SIZE] = "SIZE",
        [FTP_CMD_MDTM] = "MDTM",
        [FTP_CMD_MFMT] = "MFMT",
        [FTP_CMD_TYPE] = "TYPE",
        [FTP_CMD_USER] = "USER",
        [FTP_CMD_PASS] = "PASS",
        [FTP_CMD_PASV] = "PASV",
        [FTP_CMD_LIST] = "LIST",
        [FTP_CMD_RETR] = "RETR",
        [FTP_CMD_STOR] = "STOR",
        [FTP_CMD_DELE] = "DELE",
        [FTP_CMD_RMD] = "RMD",
        [FTP_CMD_MKD] = "MKD",
        [FTP_CMD_RNFR] = "RNFR",
        [FTP_CMD_RNTO] = "RNTO",
        [FTP_CMD_NOOP] = "NOOP",
        [FTP_CMD_QUIT] = "QUIT",
        [FTP_CMD_APPE] = "APPE",
        [FTP_CMD_NLST] = "NLST",
        [FTP_CMD_AUTH] = "AUTH",
        [FTP_CMD_STAT] = "STAT",
        [FTP_CMD_OPTS] = "OPTS",
        [FTP_CMD_ABOR] = "ABOR",
        [FTP_CMD_MODE] = "MODE",
        [FTP_CMD_STRU] = "STRU",
        [FTP_CMD_ALLO] = "ALLO",
        [FTP_CMD_EPSV] = "EPSV",
        [FTP_CMD_REST] = "REST",
    };

    if ((cmd < 0) || (cmd >= FTP_CMDS_MAX))
    {
        return "";
    }

    return names[cmd];
}

/**
 * @brief Socket handle
 *
 * @note Wrapped in a struct so that close()/read()/write()/fcntl() on a socket
 *       fails to compile. Accessed only by ftp_sock.c.
 */
typedef struct
{
    int fd;
} ftp_sock_t;

/* Initializer, also valid for static storage (a compound literal is not a constant expression) */
#define FTP_SOCK_INIT                           { .fd = -1 }

/* Value for assignment, comparison and return */
#define FTP_SOCK_INVALID                        ((ftp_sock_t)FTP_SOCK_INIT)

